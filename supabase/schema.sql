-- Starter database schema for JABER FOOTBALL QUIZ.
-- Run only after creating your own Supabase project and reviewing security policies.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Player',
  country text,
  avatar_url text,
  xp integer not null default 0,
  level integer not null default 1,
  total_points integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  quiz_mode text not null,
  question_count integer not null,
  correct_count integer not null default 0,
  wrong_count integer not null default 0,
  points integer not null default 0,
  xp_earned integer not null default 0,
  completed_at timestamptz not null default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  addressee_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'blocked')),
  created_at timestamptz not null default now(),
  unique(requester_id, addressee_id),
  check (requester_id <> addressee_id)
);

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  mode text not null,
  difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
  question_bn text not null,
  options jsonb not null,
  correct_option text not null,
  explanation_bn text,
  image_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.friendships enable row level security;
alter table public.quiz_questions enable row level security;

-- Users can read public profile information.
create policy "Profiles are viewable by everyone"
on public.profiles for select using (true);

-- Users can create and update only their own profile.
create policy "Users create own profile"
on public.profiles for insert with check (auth.uid() = id);

create policy "Users update own profile"
on public.profiles for update using (auth.uid() = id)
with check (auth.uid() = id);

-- Users can read and insert only their own quiz attempts.
create policy "Users read own attempts"
on public.quiz_attempts for select using (auth.uid() = user_id);

create policy "Users insert own attempts"
on public.quiz_attempts for insert with check (auth.uid() = user_id);

-- Published questions can be read by app users.
create policy "Published questions are readable"
on public.quiz_questions for select using (is_published = true);

-- Friendship rows are visible only to their participants.
create policy "Participants read friendships"
on public.friendships for select
using (auth.uid() = requester_id or auth.uid() = addressee_id);

create policy "Users send friend requests"
on public.friendships for insert
with check (auth.uid() = requester_id);
